#!/usr/bin/env python3
"""Write (or --check) tools/journey/golden.json: the exact adapter-call trace the journey
interpreter must produce for a set of seeded cases. Every app's interpreter unit test
replays these cases against the same canned backend (`fixture`) and compares line by line.

    golden.py [--check]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from compile import compile_bundle, test_fixture  # noqa: E402
from engine import JourneyEngine, TraceAdapter  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "golden.json")

CASES = [
    {"name": "control", "persona": "control", "sim_seed": 42, "runs": 25, "toggles": [], "infinite": False},
    {"name": "variant_a", "persona": "variant_a", "sim_seed": 42, "runs": 25, "toggles": [], "infinite": False},
    {"name": "variant_b", "persona": "variant_b", "sim_seed": 7, "runs": 25, "toggles": [], "infinite": False},
    {"name": "faults_infinite", "persona": "variant_a", "sim_seed": 1, "runs": 12,
     "toggles": ["anr", "force_quit", "crash_loop"], "infinite": True},
    {"name": "crash_loop", "persona": "control", "sim_seed": 99, "runs": 12, "toggles": ["crash_loop"], "infinite": False},
    {"name": "max_seed", "persona": "variant_b", "sim_seed": 2147483647, "runs": 4, "toggles": [], "infinite": False},
]


def build():
    bundle, _ = compile_bundle()
    fixture = test_fixture()
    cases = []
    for c in CASES:
        adapter = TraceAdapter(fixture)
        engine = JourneyEngine(bundle, adapter)
        for run in range(1, c["runs"] + 1):
            outcome = engine.run(c["persona"], run, c["sim_seed"], c["toggles"], c["infinite"])
            adapter.lines.append(f"outcome {outcome}")
        cases.append(dict(c, trace=adapter.lines))
    return {"note": "DO NOT EDIT. Generated by tools/journey/golden.py from spec/journey.yaml.",
            "fixture": fixture, "cases": cases}


def main():
    body = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else None
        if cur != body:
            print(f"{OUT} is out of date; run tools/codegen/generate.sh")
            sys.exit(1)
        print("journey golden: up to date")
        return
    with open(OUT, "w") as f:
        f.write(body)
    print(f"journey golden: wrote {OUT}")


if __name__ == "__main__":
    main()
