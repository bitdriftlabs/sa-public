#!/usr/bin/env python3
"""Generate per-language constants from spec/*.yaml.

Usage: codegen.py <language> <output-dir> [--check]
  language: kotlin (swift, ts, dart are added per platform)
  --check:  fail (exit 1) if the files on disk differ from what would be generated.

Run through tools/codegen/run.sh, which provides PyYAML in a local venv.
"""
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SPEC = os.path.join(ROOT, "spec")
HEADER = "DO NOT EDIT. Generated by tools/codegen from spec/*.yaml (run tools/codegen/run.sh)."


def load(name):
    with open(os.path.join(SPEC, name + ".yaml")) as f:
        return yaml.safe_load(f)


def const_name(s):
    """spec name -> SCREAMING_SNAKE identifier. Leading '_' (SDK-owned keys) -> SDK_ prefix."""
    prefix = "SDK_" if s.startswith("_") else ""
    s = re.sub(r"[^0-9A-Za-z]+", "_", s.lstrip("_")).strip("_").upper()
    if s[0].isdigit():
        s = "_" + s
    return prefix + s


def applies(entry, platform):
    p = entry.get("platforms")
    return p is None or platform in p


def telemetry_data(platform):
    t = load("telemetry")
    events = [e["name"] for e in t["events"] if applies(e, platform)]
    events += [e["name"] for e in t.get("sdk_events", [])]
    fields = [f["key"] for f in t["fields"] if applies(f, platform)]
    fields += [g["key"] for g in t.get("global_fields", []) if applies(g, platform)]
    spans = [s["name"] for s in t["spans"] if applies(s, platform)]
    return events, fields, spans


def uniq(names):
    seen, out = set(), []
    for n in names:
        if n not in seen:
            seen.add(n)
            out.append(n)
    return out


def check_unique(kind, names):
    consts = {}
    for n in names:
        c = const_name(n)
        if c in consts and consts[c] != n:
            raise SystemExit(f"{kind}: '{n}' and '{consts[c]}' both map to {c}")
        consts[c] = n


# ── Kotlin ───────────────────────────────────────────────────────────────────

def kt_str(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kotlin_files(package, platform="android"):
    events, fields, spans = (uniq(x) for x in telemetry_data(platform))
    check_unique("events", events)
    check_unique("fields", fields)
    check_unique("spans", spans)

    def obj(name, doc, names):
        lines = [f"/** {doc} */", f"object {name} {{"]
        for n in names:
            lines.append(f"    const val {const_name(n)} = {kt_str(n)}")
        lines.append("}")
        return "\n".join(lines)

    files = {}
    files["SpecTelemetry.kt"] = "\n".join(
        [
            f"// {HEADER}",
            f"package {package}",
            "",
            obj("SpecEvents", "Log message names (spec/telemetry.yaml events + sdk_events).", events),
            "",
            obj("SpecFields", "Field keys (spec/telemetry.yaml fields). Leading '_' keys are SDK-owned (SDK_ prefix).", fields),
            "",
            obj("SpecSpans", "Span names (spec/telemetry.yaml spans).", spans),
            "",
        ]
    )

    screens = [s for s in load("screens")["screens"] if applies(s, platform)]
    check_unique("screens", [s["id"] for s in screens])
    lines = [f"// {HEADER}", f"package {package}", "", "/** Screens (spec/screens.yaml): logScreenView name, nav route template, step. */",
             "enum class SpecScreen(val id: String, val screenName: String, val route: String, val step: Int, val loadSpan: String?) {"]
    for i, s in enumerate(screens):
        end = ";" if i == len(screens) - 1 else ","
        load_span = kt_str(s["load_span"]) if s.get("load_span") else "null"
        lines.append(f"    {const_name(s['id'])}({kt_str(s['id'])}, {kt_str(s['name'])}, {kt_str(s['route'])}, {s['step']}, {load_span}){end}")
    lines.append("}")
    lines.append("")
    files["SpecScreens.kt"] = "\n".join(lines)

    flags = [f for f in load("flags")["flags"] if applies(f, platform)]
    check_unique("flags", [f["name"] for f in flags])
    lines = [f"// {HEADER}", f"package {package}", "", "/** Feature flags (spec/flags.yaml): exposure names, mirror field keys, persona values. */", "object SpecFlags {"]
    for f in flags:
        c = const_name(f["name"])
        lines.append(f"    const val {c} = {kt_str(f['name'])}")
        if f.get("mirror_field"):
            lines.append(f"    const val {c}_FIELD = {kt_str(f['mirror_field'])}")
        if f["kind"] == "persona":
            for persona, val in f["values"].items():
                lines.append(f"    const val {c}_{const_name(persona)} = {kt_str(val)}")
    lines.append("}")
    lines.append("")
    files["SpecFlags.kt"] = "\n".join(lines)

    personas = load("personas")["personas"]
    lines = [f"// {HEADER}", f"package {package}", "", "/** Personas (spec/personas.yaml): the `variant` field label per persona. */", "object SpecPersonas {"]
    for p in personas:
        lines.append(f"    const val {const_name(p['id'])} = {kt_str(p['label'])}")
    lines.append("}")
    lines.append("")
    files["SpecPersonas.kt"] = "\n".join(lines)
    return files


# ── Swift ────────────────────────────────────────────────────────────────────

SWIFT_KEYWORDS = {
    "default", "class", "in", "is", "as", "do", "for", "if", "else", "case", "switch", "return", "self",
    "super", "init", "let", "var", "func", "import", "where", "while", "repeat", "break", "continue",
    "true", "false", "nil", "try", "throw", "throws", "static", "struct", "enum", "extension", "protocol",
    "public", "private", "internal", "open", "operator", "subscript", "typealias", "guard", "defer", "inout",
}


def camel(s):
    """spec name -> lowerCamelCase identifier (leading '_' -> 'sdk' prefix)."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", s.lstrip("_")) if p]
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])
    if s.startswith("_"):
        out = "sdk" + out[:1].upper() + out[1:]
    if out[0].isdigit():
        out = "_" + out
    return f"`{out}`" if out in SWIFT_KEYWORDS else out


def check_unique_camel(kind, names):
    seen = {}
    for n in names:
        c = camel(n)
        if c in seen and seen[c] != n:
            raise SystemExit(f"{kind}: '{n}' and '{seen[c]}' both map to {c}")
        seen[c] = n


def sw_str(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift_files(platform="ios"):
    events, fields, spans = (uniq(x) for x in telemetry_data(platform))
    for k, n in (("events", events), ("fields", fields), ("spans", spans)):
        check_unique_camel(k, n)

    def enum(name, doc, names):
        lines = [f"/// {doc}", f"enum {name} {{"]
        for n in names:
            lines.append(f"    static let {camel(n)} = {sw_str(n)}")
        lines.append("}")
        return "\n".join(lines)

    files = {}
    files["SpecTelemetry.swift"] = "\n".join(
        [
            f"// {HEADER}",
            "",
            enum("SpecEvents", "Log message names (spec/telemetry.yaml events + sdk_events).", events),
            "",
            enum("SpecFields", "Field keys (spec/telemetry.yaml fields). Leading '_' keys are SDK-owned (sdk prefix).", fields),
            "",
            enum("SpecSpans", "Span names (spec/telemetry.yaml spans).", spans),
            "",
        ]
    )

    screens = [s for s in load("screens")["screens"] if applies(s, platform)]
    check_unique_camel("screens", [s["id"] for s in screens])
    lines = [f"// {HEADER}", "", "/// Screens (spec/screens.yaml): logScreenView name, nav route template, step.",
             "enum SpecScreen: CaseIterable {"]
    for s in screens:
        lines.append(f"    case {camel(s['id'])}")
    lines += ["", "    var id: String {", "        switch self {"]
    for s in screens:
        lines.append(f"        case .{camel(s['id'])}: return {sw_str(s['id'])}")
    for prop, key in (("screenName", "name"), ("route", "route")):
        lines += ["        }", "    }", "", f"    var {prop}: String {{", "        switch self {"]
        for s in screens:
            lines.append(f"        case .{camel(s['id'])}: return {sw_str(s[key])}")
    lines += ["        }", "    }", "", "    var step: Int {", "        switch self {"]
    for s in screens:
        lines.append(f"        case .{camel(s['id'])}: return {s['step']}")
    lines += ["        }", "    }", "", "    var loadSpan: String? {", "        switch self {"]
    for s in screens:
        lines.append(f"        case .{camel(s['id'])}: return {sw_str(s['load_span']) if s.get('load_span') else 'nil'}")
    lines += ["        }", "    }", "}", ""]
    files["SpecScreens.swift"] = "\n".join(lines)

    flags = [f for f in load("flags")["flags"] if applies(f, platform)]
    check_unique_camel("flags", [f["name"] for f in flags])
    lines = [f"// {HEADER}", "", "/// Feature flags (spec/flags.yaml): exposure names, mirror field keys, persona values.", "enum SpecFlags {"]
    for f in flags:
        c = camel(f["name"])
        lines.append(f"    static let {c} = {sw_str(f['name'])}")
        if f.get("mirror_field"):
            lines.append(f"    static let {c}Field = {sw_str(f['mirror_field'])}")
        if f["kind"] == "persona":
            for persona, val in f["values"].items():
                lines.append(f"    static let {c}{camel(persona)[:1].upper() + camel(persona)[1:]} = {sw_str(val)}")
    lines += ["}", ""]
    files["SpecFlags.swift"] = "\n".join(lines)

    lines = [f"// {HEADER}", "", "/// Personas (spec/personas.yaml): the `variant` field label per persona.", "enum SpecPersonas {"]
    for p in load("personas")["personas"]:
        lines.append(f"    static let {camel(p['id'])} = {sw_str(p['label'])}")
    lines += ["}", ""]
    files["SpecPersonas.swift"] = "\n".join(lines)
    return files


# ── TypeScript ───────────────────────────────────────────────────────────────

def ts_str(v):
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_files(platform="reactnative"):
    events, fields, spans = (uniq(x) for x in telemetry_data(platform))
    for k, n in (("events", events), ("fields", fields), ("spans", spans)):
        check_unique_camel(k, n)

    def obj(name, doc, names):
        lines = [f"/** {doc} */", f"export const {name} = {{"]
        for n in names:
            lines.append(f"  {camel(n).strip('`')}: {ts_str(n)},")
        lines.append("} as const;")
        return "\n".join(lines)

    screens = [s for s in load("screens")["screens"] if applies(s, platform)]
    check_unique_camel("screens", [s["id"] for s in screens])
    lines = ["/** Screens (spec/screens.yaml): logScreenView name, template route, step; `platformRoute` is this app's navigator key. */",
             "export const SpecScreens = {"]
    for s in screens:
        pr = (s.get("platform_routes") or {}).get(platform, s["route"])
        ls = ts_str(s["load_span"]) if s.get("load_span") else "null"
        lines.append(
            f"  {camel(s['id']).strip('`')}: {{id: {ts_str(s['id'])}, screenName: {ts_str(s['name'])}, "
            f"route: {ts_str(s['route'])}, platformRoute: {ts_str(pr)}, step: {s['step']}, loadSpan: {ls}}},"
        )
    lines.append("} as const;")
    screens_block = "\n".join(lines)

    flags = [f for f in load("flags")["flags"] if applies(f, platform)]
    check_unique_camel("flags", [f["name"] for f in flags])
    lines = ["/** Feature flags (spec/flags.yaml): exposure names, mirror field keys, persona values. */", "export const SpecFlags = {"]
    for f in flags:
        c = camel(f["name"]).strip("`")
        lines.append(f"  {c}: {ts_str(f['name'])},")
        if f.get("mirror_field"):
            lines.append(f"  {c}Field: {ts_str(f['mirror_field'])},")
        if f["kind"] == "persona":
            for persona, val in f["values"].items():
                pc = camel(persona)
                lines.append(f"  {c}{pc[:1].upper() + pc[1:]}: {ts_str(val)},")
    lines.append("} as const;")
    flags_block = "\n".join(lines)

    lines = ["/** Personas (spec/personas.yaml): the `variant` field label per persona. */", "export const SpecPersonas = {"]
    for p in load("personas")["personas"]:
        lines.append(f"  {camel(p['id'])}: {ts_str(p['label'])},")
    lines.append("} as const;")

    body = "\n\n".join(
        [
            f"// {HEADER}",
            obj("SpecEvents", "Log message names (spec/telemetry.yaml events + sdk_events).", events),
            obj("SpecFields", "Field keys (spec/telemetry.yaml fields). Leading '_' keys are SDK-owned (sdk prefix).", fields),
            obj("SpecSpans", "Span names (spec/telemetry.yaml spans).", spans),
            screens_block,
            flags_block,
            "\n".join(lines),
        ]
    )
    return {"spec.ts": body + "\n"}


LANGS = {"kotlin": kotlin_files, "swift": swift_files, "ts": ts_files}


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if len(args) < 2 or args[0] not in LANGS:
        raise SystemExit(__doc__)
    lang, out = args[0], args[1]
    package = args[2] if len(args) > 2 else None
    files = LANGS[lang](package) if package else LANGS[lang]()
    bad = []
    for name, body in files.items():
        path = os.path.join(out, name)
        if check:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != body:
                bad.append(path)
        else:
            os.makedirs(out, exist_ok=True)
            with open(path, "w") as f:
                f.write(body)
    if check:
        if bad:
            print("generated files out of date:\n  " + "\n  ".join(bad))
            print("run tools/codegen/run.sh to regenerate")
            sys.exit(1)
        print(f"{lang}: up to date ({len(files)} files)")
    else:
        print(f"{lang}: wrote {len(files)} files to {out}")


if __name__ == "__main__":
    main()
